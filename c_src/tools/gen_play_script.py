"""Write the played-game scenarios in tests/scenarios: scripts for the oracle and
for the C port's verifier.

They are generated so they can be long and regular: a coin, a start, a Death
Star chosen, then the stick swept in a slow figure while the two triggers and
the two thumb buttons are pulled in turn.  The option switches give nine
shields, easy play and three bonus shields.  Nothing here is random: the same
script every time.

    play.txt     the plain game: the scripted player gets through the space wave
                 and dies over the surface
    waves.txt    the same player kept alive (the script pokes the shield count
                 S.GAS back up) so the game runs on through the surface, the
                 towers and the trench; where the trench comes round again the
                 script sets PHASE to the Death Star explosion, as a hit on the
                 exhaust port would, and the next wave follows
    hiscore.txt  the game with a score poked in and the shields left to run
                 out: game over, initials entered with the stick and trigger,
                 the high score table, then the attract mode with a coin in

    python tools/gen_play_script.py [PLAY_PASSES (1400)]
"""
import math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCEN = os.path.join(HERE, "..", "tests", "scenarios")

S_GAS = 0x4860
PHASE = 0x4841
S_SC65 = 0x485D
PHS_DX1 = 0x11
BS_WAV, GD_WAV, SP_WAV, GM_WAV = 0x4B12, 0x4B13, 0x4B14, 0x4B15

def player(first, last, buttons=("firel", "firer", "thumbl", "firer", "firel", "thumbr"),
           stick=(0x30, 0.21, 0x24, 0.13, 1.0)):
    """the stick and the buttons from pass `first` to pass `last`.
    stick: yaw amplitude and rate, pitch amplitude and rate, pitch phase."""
    ay, fy, ap, fp, ph = stick
    ev = []
    k = 0
    for p in range(first + 10, last, 5):
        b = buttons[k % len(buttons)]
        k += 1
        ev.append((p, "%s 1" % b))
        ev.append((p + 2, "%s 0" % b))
    prev = (None, None)
    for p in range(first, last, 4):
        t = (p - first) / 4.0
        yaw = 0x80 + int(round(ay * math.sin(t * fy)))
        pitch = 0x80 + int(round(ap * math.sin(t * fp + ph)))
        if yaw != prev[0]:
            ev.append((p, "yaw 0x%02X" % yaw))
        if pitch != prev[1]:
            ev.append((p, "pitch 0x%02X" % pitch))
        prev = (yaw, pitch)
    return ev

START = ["0 dsw0 0xB3",
         "30 coinl 1", "32 coinl 0",
         "60 firel 1", "62 firel 0",
         "100 firel 1", "102 firel 0"]

def write(name, head, passes, ev):
    L = ["# " + h for h in head] + ["#", "# run with:  --frames %d" % passes]
    ev = [(int(s.split()[0]), s.split(None, 1)[1]) for s in START] + ev
    ev = sorted(ev, key=lambda e: e[0])           # stable: lines of one pass keep their order
    L += ["%d %s" % e for e in ev]
    out = os.path.join(SCEN, name)
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("wrote %s: %d lines" % (os.path.normpath(out), len(L)))

def play(passes):
    write("play.txt",
          ["A played game (generated by tools/gen_play_script.py - edit that, not this).",
           "Nine shields, easy, three bonus shields; coin, start, choose a Death Star,",
           "then the stick swept in a slow figure with the triggers and thumbs in turn."],
          passes, player(120, passes - 20))

def waves(name, passes, explode=(), yaw=None, quiet=(), pokes=(), stick=None):
    """yaw: where the stick points when the Death Star is chosen (left the easy
    one, right the hard one).  quiet: (first, last) pass ranges with no button
    pulled - the trench flown on the Force.  pokes: (pass, address, value, why)."""
    ev = [e for e in (player(120, passes - 20, stick=stick) if stick else player(120, passes - 20))
          if not (e[1].split()[0] not in ("yaw", "pitch") and any(a <= e[0] <= b for a, b in quiet))]
    if yaw is not None:
        ev.append((66, "yaw 0x%02X" % yaw))
    for p in range(300, passes - 20, 25):
        ev.append((p, "poke 0x%04X 6" % S_GAS))
    for p in explode:
        ev.append((p, "poke 0x%04X 0x%02X" % (PHASE, PHS_DX1)))
    head = ["The played game kept alive (generated by tools/gen_play_script.py).",
            "The shield count S.GAS is poked back to 6 every 25 passes."]
    if yaw is not None:
        head.append("The stick is at 0x%02X when the Death Star is chosen." % yaw)
    if explode:
        head.append("At passes %s PHASE is set to the Death Star explosion." % ", ".join(str(p) for p in explode))
    if quiet:
        head.append("No button is pulled in passes %s." % ", ".join("%d-%d" % q for q in quiet))
    if stick:
        head.append("Stick: yaw %d at rate %.2f, pitch %d at rate %.2f, phase %.1f." % tuple(stick))
    for p, addr, val, why in pokes:
        ev.append((p, "poke 0x%04X 0x%02X" % (addr, val)))
        head.append("Pass %d: $%04X = $%02X, %s." % (p, addr, val, why))
    write(name, head, passes, ev)

def hiscore(passes, die_from):
    ev = player(120, passes - 20, buttons=("firel", "firer", "firel", "thumbr"))
    ev.append((300, "poke 0x%04X 0x98" % S_SC65))
    write("hiscore.txt",
          ["A game that ends with a high score (generated by tools/gen_play_script.py).",
           "The score's high digits are poked at pass 300; the shields run out on their own;",
           "the stick and the trigger then enter initials."],
          passes, ev)

def die(name, passes, shields_until, where):
    """the kept-alive game, then no shield left at pass `shields_until`"""
    ev = player(120, passes - 20)
    for p in range(300, shields_until, 25):
        ev.append((p, "poke 0x%04X 6" % S_GAS))
    ev.append((shields_until, "poke 0x%04X 0" % S_GAS))
    write(name,
          ["A game lost %s (generated by tools/gen_play_script.py)." % where,
           "The shield count S.GAS is poked to 6 every 25 passes up to pass %d and to 0" % shields_until,
           "there: the next hit ends the game."],
          passes, ev)

def operator(passes):
    """the operator's screens: statistics, then the option page with the stick
    and the trigger changing options, then back to the attract mode"""
    ev = [(100, "test 1"), (300, "coinaux 1"), (304, "coinaux 0")]
    ev += player(320, 700)
    ev += [(720, "test 0")]
    L = ["# The operator's screens (generated by tools/gen_play_script.py): the self-test",
         "# switch in the attract mode shows the statistics, the aux coin switch the",
         "# option page; the stick and the trigger change options; switch off, attract.",
         "#", "# run with:  --frames %d" % passes]
    L += ["%d %s" % e for e in sorted(ev, key=lambda e: e[0])]
    with open(os.path.join(SCEN, "operator.txt"), "w", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("wrote operator.txt: %d lines" % len(L))

def operator_game(passes):
    """a game played and lost first, so the statistics page has a game to
    average (DIVIDE); then the option page, where the trigger runs the NOVRAM
    test, which STOREs.  Run with --nvram-out: the image is what a machine
    with a game on its books powers up with (scenario nvboot)."""
    ev = player(120, 480)
    ev.append((300, "poke 0x%04X 0" % S_GAS))
    ev += [(520, "test 1"), (720, "coinaux 1"), (724, "coinaux 0")]
    ev += player(740, 1100)
    ev += [(1120, "test 0")]
    write("operator_game.txt",
          ["A game, then the operator's screens (generated by tools/gen_play_script.py).",
           "No shields from pass 300, so the game is lost in the space wave; the self-test",
           "switch at pass 520 shows the statistics with one game played, the aux coin",
           "switch the option page; the stick and the trigger change options and run the",
           "NOVRAM test.  Run with --nvram-out FILE to keep the NOVRAM for nvboot.txt."],
          passes, ev)

def nvboot(passes):
    """power-on with the NOVRAM operator_game left: the checksums are good."""
    ev = [(150, "test 1"), (350, "test 0")]
    L = ["# Power-on with a NOVRAM that holds data (generated by tools/gen_play_script.py):",
         "# run with --nvram-in FILE, the file operator_game.txt wrote.  The attract mode,",
         "# then the statistics page and back.",
         "#", "# run with:  --frames %d --nvram-in FILE" % passes]
    L += ["%d %s" % e for e in ev]
    with open(os.path.join(SCEN, "nvboot.txt"), "w", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("wrote nvboot.txt: %d lines" % len(L))

def sndtest(passes):
    """the sound board's own test switch, closed once it is running (closed at
    power-on it runs the board's RAM and ROM test instead): its mainline steps through every
    entry of its command table (tones, effects, music, speech), one every two
    or four seconds, while the main board runs the attract mode"""
    L = ["# The sound board's self-test switch (generated by tools/gen_play_script.py):",
         "# the sound program plays every entry of its command table in turn.",
         "#", "# run with:  --frames %d" % passes,
         "40 sndtest 1"]
    with open(os.path.join(SCEN, "sndtest.txt"), "w", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("wrote sndtest.txt: %d lines" % len(L))

def diag(step=20):
    """the diagnostics: both switches on at power-on, then the option switches
    (read complemented) select each test in turn; a pass is an arrival at DIAGLP
    ($FD07).  Both switches off at the end: HANG, the watchdog, the game."""
    tests = [0x00, 0x80] + list(range(0xC0, 0xC8)) + [0xC6] + list(range(0xE0, 0xEC)) + \
            list(range(0xF0, 0xF6)) + [0xF8, 0xF9, 0x40, 0x00]
    L = ["# The diagnostics (generated by tools/gen_play_script.py): test and diagnostic",
         "# switches on at power-on; option bank 1 selects each test in turn, %d arrivals" % step,
         "# at DIAGLP each (including numbers that are errors); then both switches off:",
         "# HANG, the watchdog bites, and the game starts.",
         "#", "# run with:  --diag-pc FD07 --allow-watchdog --frames %d" % (step * len(tests) + 120),
         "0 test 1", "0 diag 1", "0 dsw0 0x%02X" % (~tests[0] & 0xFF)]
    p = step
    for t in tests[1:]:
        L.append("%d dsw0 0x%02X" % (p, ~t & 0xFF))
        p += step
    L += ["%d test 0" % p, "%d diag 0" % p, "%d dsw0 0xB3" % p]
    with open(os.path.join(SCEN, "diag.txt"), "w", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("wrote diag.txt: %d lines, %d passes" % (len(L), p + 120))


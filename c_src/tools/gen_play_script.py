    waves("waves_first.txt", 1600, pokes=[(290, SP_WAV, 0, "the first space wave: straight to the trench")])
    waves("waves_force.txt", 2400, yaw=0xE0, quiet=[(1400, 1900)])
    waves("waves_six.txt", 1500, pokes=[(290, a, 6, "wave six: the surface has bishop buildings")
                                         for a in (BS_WAV, GD_WAV, SP_WAV, GM_WAV)])
    # the three alien records' AS.HTA: a hit that does not destroy is the code for hitting Darth Vader's ship,
    # which the scripted player never managed to hit
    waves("waves_tough.txt", 1000, pokes=[(p, a, 5, "an alien ship that takes five hits")
                                          for p in range(300, 660, 60) for a in (0x4907, 0x4920, 0x4939)])
    waves("waves_five.txt", 1000, pokes=[(290, SP_WAV, 4, "space wave five: 'look at the size of that thing'")])
    hiscore(3600, 0)
    die("die_space.txt", 900, 300, "in the space wave")
    die("die_trench.txt", 2200, 1420, "in the trench")
    operator(900)
    operator_game(1300)
